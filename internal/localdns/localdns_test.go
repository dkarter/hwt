func TestReloadFailuresRestoreExactState(t *testing.T) {
	cfg := testConfig(t)
	setup, err := Setup(cfg)
	if err != nil {
		t.Fatal(err)
	}
	before := snapshots(t, setup.Paths)
	dirs := directories(t, "repo", "work")
	cfg.Reload = []string{stub(t, `echo 'reload exploded' >&2; exit 23`)}
	_, err = Register(cfg, Registration{Repository: dirs[0], Worktree: dirs[1], Services: map[string]int{"web": 80}})
	if err == nil || !strings.Contains(err.Error(), "reload exploded") {
		t.Fatalf("error = %v", err)
	}
	for path, want := range before {
		got, _ := os.ReadFile(path)
		if !reflect.DeepEqual(got, want) {
			t.Fatalf("%s was not restored exactly", path)
		}
	}
	cfg.Reload = []string{filepath.Join(t.TempDir(), "missing")}
	_, err = Register(cfg, Registration{Repository: dirs[0], Worktree: dirs[1], Services: map[string]int{"web": 80}})
	if err == nil || !strings.Contains(err.Error(), "was not found") {
		t.Fatalf("missing executable error = %v", err)
	}
}

