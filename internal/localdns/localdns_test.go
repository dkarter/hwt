func testConfig(t *testing.T) Config {
	t.Helper()
	t.Setenv("XDG_STATE_HOME", t.TempDir())
	toolDir := t.TempDir()
	for _, tool := range []string{"caddy", "dnsmasq"} {
		if err := os.WriteFile(filepath.Join(toolDir, tool), []byte("#!/bin/sh\nexit 0\n"), 0o700); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("PATH", toolDir)
	return Config{Enabled: true, Domain: "HWT.Test."}
}

func directories(t *testing.T, names ...string) []string {
	t.Helper()
	root := t.TempDir()
	result := make([]string, len(names))
	for index, name := range names {
		result[index] = filepath.Join(root, name)
		if err := os.MkdirAll(result[index], 0o700); err != nil {
			t.Fatal(err)
		}
	}
	return result
}

func register(t *testing.T, cfg Config, repository, worktree string, services map[string]int) Result {
	t.Helper()
	result, err := Register(cfg, Registration{Repository: repository, Worktree: worktree, Services: services})
	if err != nil {
		t.Fatal(err)
	}
	return result
}

func TestSanitizeAndHostnameDeterminism(t *testing.T) {
	if got := sanitize("  My_REPO...Name  ", "repo"); got != "my-repo-name" {
		t.Fatalf("sanitize = %q", got)
	}
	if got := sanitize("日本語", "repo"); got != "repo" {
		t.Fatalf("fallback = %q", got)
	}
	paths := directories(t, "Repository With A Very Long Name That Keeps Going 123456789", "Feature/API")
	host := baseHostname(paths[0], paths[1], "hwt.test")
	if host != baseHostname(paths[0], paths[1], "hwt.test") {
		t.Fatal("hostname is not deterministic")
	}
	label := strings.Split(host, ".")[0]
	if len(label) > 63 || !strings.HasSuffix(host, ".hwt.test") {
		t.Fatalf("invalid hostname %q", host)
	}
	digest := sha256.Sum256([]byte(paths[0] + "\x00" + paths[1]))
	if !strings.HasSuffix(label, "-"+hex.EncodeToString(digest[:])[:12]) {
		t.Fatalf("hostname %q lacks expected path digest", host)
	}
	other := directories(t, "Feature/API")[0]
	if baseHostname(paths[0], other, "hwt.test") == host {
		t.Fatal("distinct canonical paths produced the same hostname")
	}
}

func TestHostnameCanonicalizesExistingPaths(t *testing.T) {
	dirs := directories(t, "Repo Name", "Work Tree")
	aliasRoot := t.TempDir()
	repositoryAlias := filepath.Join(aliasRoot, "repository")
	worktreeAlias := filepath.Join(aliasRoot, "worktree")
	if err := os.Symlink(dirs[0], repositoryAlias); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(dirs[1], worktreeAlias); err != nil {
		t.Fatal(err)
	}

	got, err := Hostname(repositoryAlias, worktreeAlias, "HWT.Test.")
	if err != nil {
		t.Fatal(err)
	}
	repository, _ := filepath.EvalSymlinks(dirs[0])
	worktree, _ := filepath.EvalSymlinks(dirs[1])
	want := baseHostname(repository, worktree, "hwt.test")
	if got != want {
		t.Fatalf("Hostname() = %q, want %q", got, want)
	}
	if _, err := Hostname(repositoryAlias, filepath.Join(aliasRoot, "missing"), "hwt.test"); err == nil || !strings.Contains(err.Error(), "canonicalize worktree") {
		t.Fatalf("missing worktree error = %v", err)
	}
	if _, err := Hostname(repositoryAlias, worktreeAlias, "localhost"); err == nil || !strings.Contains(err.Error(), "invalid") {
		t.Fatalf("invalid domain error = %v", err)
	}
	if _, err := Hostname(repositoryAlias, worktreeAlias, "single"); err == nil || !strings.Contains(err.Error(), "two labels") {
		t.Fatalf("single-label domain error = %v", err)
	}
}

func TestSetupGenerationStatusAndModes(t *testing.T) {
	cfg := testConfig(t)
	setup, err := Setup(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(setup.DNSMasqInclude, setup.Paths.DNSMasq) || !strings.Contains(setup.CaddyImport, setup.Paths.Caddyfile) {
		t.Fatalf("setup guidance does not contain generated paths: %#v", setup)
	}
	if filepath.Base(filepath.Dir(setup.Paths.StateDir)) != "hwt" || filepath.Base(setup.Paths.StateDir) != "local-dns" {
		t.Fatalf("state directory does not match documented hwt/local-dns layout: %s", setup.Paths.StateDir)
	}
	dnsmasq, err := os.ReadFile(setup.Paths.DNSMasq)
	if err != nil {
		t.Fatal(err)
	}
	if string(dnsmasq) != "# Generated by hwt. Do not edit.\naddress=/.hwt.test/127.0.0.1\n" {
		t.Fatalf("dnsmasq = %q", dnsmasq)
	}
	for _, path := range []string{setup.Paths.Registry, setup.Paths.DNSMasq, setup.Paths.Caddyfile} {
		info, err := os.Stat(path)
		if err != nil {
			t.Fatal(err)
		}
		if info.Mode().Perm() != 0o600 {
			t.Fatalf("%s mode = %o", path, info.Mode().Perm())
		}
	}
	status, err := Status(cfg)
	if err != nil || len(status.Entries) != 0 {
		t.Fatalf("status = %#v, %v", status, err)
	}
}

func TestRegisterGeneratesStableSortedConfiguration(t *testing.T) {
	cfg := testConfig(t)
	paths := directories(t, "Repo_Name", "Work Tree")
	result := register(t, cfg, paths[0], paths[1], map[string]int{"Web UI": 4000, "api": 3000})
	if result.Hostname == "" || result.URLs["Web UI"] != "http://web-ui."+result.Hostname {
		t.Fatalf("result = %#v", result)
	}
	caddy, err := os.ReadFile(result.Paths.Caddyfile)
	if err != nil {
		t.Fatal(err)
	}
	want := fmt.Sprintf("# Generated by hwt. Do not edit.\nhttp://api.%s {\n\treverse_proxy 127.0.0.1:3000\n}\n\nhttp://web-ui.%s {\n\treverse_proxy 127.0.0.1:4000\n}\n\n", result.Hostname, result.Hostname)
	if string(caddy) != want {
		t.Fatalf("Caddyfile:\n%s\nwant:\n%s", caddy, want)
	}
	first, _ := os.ReadFile(result.Paths.Registry)
	register(t, cfg, paths[0], paths[1], map[string]int{"api": 3000, "Web UI": 4000})
	second, _ := os.ReadFile(result.Paths.Registry)
	if !reflect.DeepEqual(first, second) {
		t.Fatal("idempotent registration changed registry bytes")
	}
}

func TestConcurrentRegistrationDoesNotLoseEntries(t *testing.T) {
	cfg := testConfig(t)
	repository := directories(t, "repo")[0]
	root := t.TempDir()
	const count = 16
	var wait sync.WaitGroup
	errors := make(chan error, count)
	for index := range count {
		worktree := filepath.Join(root, fmt.Sprintf("work-%02d", index))
		if err := os.Mkdir(worktree, 0o700); err != nil {
			t.Fatal(err)
		}
		wait.Add(1)
		go func() {
			defer wait.Done()
			_, err := Register(cfg, Registration{Repository: repository, Worktree: worktree, Services: map[string]int{"web": 8000}})
			errors <- err
		}()
	}
	wait.Wait()
	close(errors)
	for err := range errors {
		if err != nil {
			t.Fatal(err)
		}
	}
	status, err := Status(cfg)
	if err != nil || len(status.Entries) != count {
		t.Fatalf("got %d registrations: %v", len(status.Entries), err)
	}
}

