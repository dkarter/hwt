func TestReleaseAndTeardownRollback(t *testing.T) {
	cfg := testConfig(t)
	dirs := directories(t, "repo", "work")
	result := register(t, cfg, dirs[0], dirs[1], map[string]int{"web": 80})
	before := snapshots(t, result.Paths)
	failing := stub(t, "exit 1")
	cfg.Reload = []string{failing}
	if err := Release(dirs[1], cfg); err == nil {
		t.Fatal("release succeeded despite failed reload")
	}
	for path, want := range before {
		got, _ := os.ReadFile(path)
		if !reflect.DeepEqual(got, want) {
			t.Fatalf("release did not restore %s", path)
		}
	}
	if err := Teardown(Config{Enabled: true, Domain: cfg.Domain}, false); err == nil || !strings.Contains(err.Error(), "refusing") {
		t.Fatalf("teardown error = %v", err)
	}
	if err := Teardown(cfg, true); err == nil {
		t.Fatal("teardown succeeded despite failed reload")
	}
	for path, want := range before {
		got, _ := os.ReadFile(path)
		if !reflect.DeepEqual(got, want) {
			t.Fatalf("teardown did not restore %s", path)
		}
	}
	if err := Teardown(Config{Enabled: true, Domain: cfg.Domain}, true); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{result.Paths.Registry, result.Paths.DNSMasq, result.Paths.Caddyfile} {
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Fatalf("owned file remains: %s", path)
		}
	}
}

